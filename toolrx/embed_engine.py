#!/usr/bin/env python3
"""Generate web/engine2d.embed.js from web/engine2d.js.

The browser needs the engine source as a string so a bundled preview can inline
it, but the engine itself must stay a normal script for generated projects. This
script is the single bridge: edit engine2d.js, then run it (docs/build.py does).

    python3 toolrx/embed_engine.py
"""
import json
import pathlib

ROOT = pathlib.Path(__file__).resolve().parent.parent
ENGINE = ROOT / "toolrx" / "web" / "engine2d.js"
EMBED = ROOT / "toolrx" / "web" / "engine2d.embed.js"
BANNER = ("/* generated by toolrx/embed_engine.py from engine2d.js — do not edit */\n")


def main():
    source = ENGINE.read_text(encoding="utf-8")
    EMBED.write_text(BANNER + "self.toolrxEngine2dSource = "
                     + json.dumps(source) + ";\n", encoding="utf-8")
    print(f"wrote {EMBED} ({ENGINE.stat().st_size} bytes of engine source)")


if __name__ == "__main__":
    main()
