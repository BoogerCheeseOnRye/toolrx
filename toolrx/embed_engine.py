#!/usr/bin/env python3
"""Generate the *_source.js embeds from the shared runtimes.

The browser needs each runtime as a string so a bundled preview can inline it,
but generated projects load the same file normally. Edit the runtime, then run
this (docs/build.py does) so previews never drift from the shipped files.

    python3 toolrx/embed_engine.py
"""
import json
import pathlib

ROOT = pathlib.Path(__file__).resolve().parent.parent
WEB = ROOT / "toolrx" / "web"
BANNER = "/* generated by toolrx/embed_engine.py from {src} — do not edit */\n"

TARGETS = [
    ("engine2d.js", "toolrxEngine2dSource"),
    ("engine3d.js", "toolrxEngine3dSource"),
    ("worldgen.js", "toolrxWorldgenSource"),
    ("rpg2.js", "toolrxRpg2Source"),
]


def main():
    total = 0
    for name, var in TARGETS:
        src = WEB / name
        if not src.exists():
            continue
        out = WEB / name.replace(".js", ".embed.js")
        source = src.read_text(encoding="utf-8")
        out.write_text(BANNER.format(src=name) + "self." + var + " = "
                       + json.dumps(source) + ";\n", encoding="utf-8")
        print(f"wrote {out.name} ({len(source)} chars from {name})")
        total += 1
    if not total:
        raise SystemExit("no runtime sources found")


if __name__ == "__main__":
    main()
